export function calculatePriorityScore(
  severity: SeverityLevel,
  publicRiskScore: number = 5,
  reportsCount: number = 1,
  locationSensitivityScore: number = 5
): number {
  const severityMap: Record<SeverityLevel, number> = {
    low: 10,
    medium: 30,
    high: 60,
    critical: 90,
  };

  let score = severityMap[severity] || 30;
  score += Math.min(reportsCount * 5, 25);

  const nearSensitivePlace = locationSensitivityScore >= 8 || publicRiskScore >= 8;
  if (nearSensitivePlace) {
    score += 20;
  }

  return Math.min(100, Math.round(score));
}

